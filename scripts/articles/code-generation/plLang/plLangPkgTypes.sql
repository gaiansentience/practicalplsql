
set serveroutput on;
declare
    subtype plLang is json;
    subtype plSqlCode is clob;
    subtype identifier is varchar2(128);
    myDef plLang;
    myCode plsqlCode;
    type pDef is record(
        pName identifier,
        pDirection varchar2(20),
        pType identifier,
        pDefault varchar2(1000)
    );
--    type stDef is record(
--        stName varchar2(128),
--        stType varchar2(128),
--        isNullable boolean);
--    type tDef is record(
--        tName varchar2(128),
